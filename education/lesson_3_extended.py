def withdraw_money():
    global balance
    try:
        amount = int(input("Сколько денег снять? "))
        if amount  < 0 :
            print("Сумма не может быть отрицательной.")
            return
        if amount  > balance:
            print("Недостаточно средств.")
        else:
            balance -= amount
            print(f"Баланс: {balance}")
    except ValueError:
        print("Ошибка: введите число.")

